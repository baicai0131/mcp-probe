import fs from 'node:fs';
import path from 'node:path';

/**
 * Generates Markdown summary report
 * @param {import('../runner/test-runner.js').SuiteResult} suiteResult
 * @returns {string}
 */
export function generateMarkdownReport(suiteResult) {
  const statusBadge = suiteResult.failedTests === 0 ? '🟢 **PASSED**' : '🔴 **FAILED**';
  const duration = (suiteResult.durationMs / 1000).toFixed(2);

  let md = `# MCP Probe Test Report\n\n`;
  md += `**Suite:** ${suiteResult.suiteName}  \n`;
  if (suiteResult.description) {
    md += `**Description:** ${suiteResult.description}  \n`;
  }
  md += `**Status:** ${statusBadge}  \n`;
  md += `**Summary:** ${suiteResult.passedTests}/${suiteResult.totalTests} passed (${duration}s)  \n`;
  if (suiteResult.serverInfo) {
    md += `**Server:** \`${suiteResult.serverInfo.name || 'unknown'}@${suiteResult.serverInfo.version || '0.0.0'}\` (Protocol: \`${suiteResult.protocolVersion}\`)  \n`;
  }
  md += `\n---\n\n`;

  md += `### Test Results\n\n`;
  md += `| Status | Test Name | Tool / Type | Duration | Details |\n`;
  md += `| :---: | :--- | :--- | :---: | :--- |\n`;

  for (const tc of suiteResult.testResults) {
    const icon = tc.passed ? '✅' : '❌';
    const tool = tc.tool ? `\`${tc.tool}\`` : tc.type;
    const dur = `${tc.durationMs}ms`;
    let detail = 'All assertions passed';

    if (!tc.passed) {
      const failed = tc.assertions.filter((a) => !a.passed);
      detail = tc.error || failed.map((a) => a.message).join('<br/>');
    }

    md += `| ${icon} | **${tc.name}** | ${tool} | ${dur} | ${detail} |\n`;
  }

  md += `\n*Generated by [mcp-probe](https://github.com/baicai0131/mcp-probe)*\n`;
  return md;
}

/**
 * Writes Markdown report to file
 * @param {import('../runner/test-runner.js').SuiteResult} suiteResult
 * @param {string} outputPath
 */
export function writeMarkdownReport(suiteResult, outputPath) {
  const resolved = path.resolve(process.cwd(), outputPath);
  fs.mkdirSync(path.dirname(resolved), { recursive: true });
  fs.writeFileSync(resolved, generateMarkdownReport(suiteResult), 'utf-8');
}
